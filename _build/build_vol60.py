def infobox(rows, contact):
    r = "".join(f'<div class="ib-row"><dt>{E(k)}</dt><dd>{"<br>".join(E(x) for x in v)}</dd></div>' for k, v in rows)
    return f'<dl class="infobox">{r}<div class="ib-row contact"><dt>문의</dt><dd>{E(contact)}</dd></div></dl>'

